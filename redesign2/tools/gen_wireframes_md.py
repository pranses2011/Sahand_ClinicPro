def cell_text(cell) -> str:
    """نمایشِ متنیِ یک سلول"""
    if isinstance(cell, (list, tuple)):
        tag = str(cell[0]) if cell else ""
        if tag in ("chip", "who", "date", "num", "money"):
            return str(cell[1] if len(cell) > 1 else "")
        return " ".join(str(c) for c in cell[1:]) if len(cell) > 1 else ""
    return str(cell)


def table_kpis(f: dict) -> str:
    if not f.get("kpis"):
        return ""
    L = ["| آیکون | شاخص | مقدار | روند | رنگِ تاکیدی |", "|---|:--:|:--:|:--:|---|"]
    for k in f["kpis"]:
        ic = ikey(k.get("ic")) or "—"
        L.append(f"| `{ic}` | {k['l']} | **{k['v']}** | {k.get('tr') or '—'} | {k.get('ac') or '—'} |")
    return "\n".join(L)


def table_toolbar(f: dict) -> str:
    if not f.get("toolbar"):
        return ""
    L = ["| # | برچسب | نوع | پهنا | مقدارِ نمونه | گزینه‌ها |", "|:--:|---|---|:--:|---|---|"]
    for i, t in enumerate(f["toolbar"], 1):
        opts = "، ".join(str(o) for o in (t.get("opts") or [])) or "—"
        L.append(f"| {i} | {t.get('l') or '—'} | `{t.get('k')}` | {t.get('w') or '—'} "
                 f"| {t.get('v') or '—'} | {opts} |")
    return "\n".join(L)


