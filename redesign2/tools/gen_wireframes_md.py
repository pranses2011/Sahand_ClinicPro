def build(f: dict) -> str:
    ic = ikey(f.get("icon"))
    L = [
        f"# {GROUP_ICON.get(f['group'], '•')} {f['title']} — `{f['name']}`",
        "",
        f"> [{f['group']}] · کهن‌الگوی `{f['arch']}` ({ARCH_FA.get(f['arch'], f['arch'])}) "
        f"· آیکون `{ic or '—'}`",
        "",
        "| پیوند | نشانی |",
        "|---|---|",
        f"| وایرفریمِ زنده | [`01-wireframes-html/{f['name']}.html`](../01-wireframes-html/{f['name']}.html) |",
        f"| View | [`03-views/{f['name']}.xaml`](../03-views/{f['name']}.xaml) |",
        f"| ViewModel | [`04-viewmodels/{vm_name(f)}.cs`](../04-viewmodels/{vm_name(f)}.cs) |",
        "",
    ]
    if f.get("subtitle"):
        L += [f"**{f['subtitle']}**", ""]
    if f.get("notes"):
        L += ["## 📝 شرح", "", f["notes"], ""]

    L += ["## 🖼 چیدمان", "", "```", layout_diagram(f), "```", ""]

    if f.get("kpis"):
        L += ["## 📊 شاخص‌های کلیدی", "", table_kpis(f), ""]
    if f.get("toolbar"):
        L += ["## 🔍 فیلترها", "", table_toolbar(f), ""]
    if f.get("tabs"):
        L += ["## 🗂 تب‌ها", "", table_tabs(f), ""]
    if f.get("sections"):
        L += ["## 📋 فیلدها", "",
              "> پهنا بر پایه‌ی شبکه‌ی ۱۲ ستونه است: «بزرگیِ عنصر متناسب با کارکرد».",
              "", table_fields(f), ""]
    if f.get("cols"):
        L += ["## 📐 ستون‌های جدول", "", table_cols(f), ""]
    if f.get("rows"):
        L += ["## 🧪 دادهٔ نمونه", "", table_rows(f), ""]
    if f.get("aside"):
        L += ["## 📌 پانلِ کناری", "",
              f"**{f['aside'].get('title') or ''}** "
              f"(آیکون `{ikey(f['aside'].get('icon')) or '—'}`)",
              "", "| کلید | مقدار |", "|---|---|"]
        for k, v in f["aside"].get("fields") or []:
            L.append(f"| {k} | {v} |")
        L.append("")
    if f.get("total"):
        t = f["total"]
        L += ["## 🧾 جمع", "", "| مورد | مقدار |", "|---|---|"]
        for label, key in (("تعداد اقلام", "items"), ("جمع کل", "subtotal"),
                           ("تخفیف", "discount"), ("قابل پرداخت", "total")):
            if t.get(key):
                L.append(f"| {label} | **{t[key]}** |")
        L.append("")
    if f.get("actions"):
        L += ["## ⚡ اقدام‌ها", "", table_actions(f), ""]
    if f.get("rel"):
        L += ["## 🔗 ارتباطات", "", table_relations(f), "", relations_minigraph(f), ""]

    L += ["---", "", "این فایل با `tools/gen_wireframes_md.py` ساخته شده است."]
    return "\n".join(L) + "\n"


def index() -> str:
    L = ["# 📐 ۰۲-وایرفریم‌های متنی — ۸۱ وایرفریم", "",
         "> همان محتوای وایرفریم‌های HTML، در قالبی که در دیفِ گیت خوانا باشد.",
         ">", f"> مجموع: **{len(S.FORMS)}** وایرفریم.", "",
         "| # | صفحه | گروه | کهن‌الگو | فایل |", "|:--:|---|---|---|---|"]
    for i, f in enumerate(sorted(S.FORMS, key=lambda x: (x["group"], x["title"])), 1):
        L.append(f"| {i} | {GROUP_ICON.get(f['group'], '•')} {f['title']} | {f['group']} "
                 f"| `{f['arch']}` | [`{f['name']}.md`]({f['name']}.md) |")
    L += ["", "---", "", "این فایل با `tools/gen_wireframes_md.py` ساخته شده است."]
    return "\n".join(L) + "\n"


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for f in S.FORMS:
        (OUT / f"{f['name']}.md").write_text(build(f), encoding="utf-8")
    (OUT / "README.md").write_text(index(), encoding="utf-8")
    print(f"✅ {len(S.FORMS)} وایرفریمِ متنی در {OUT.relative_to(ROOT)} تولید شد")


if __name__ == "__main__":
    main()
