using Sahand.ClinicPro.Domain.Common;

namespace Sahand.ClinicPro.Domain.Entities.Security;

/// <summary>
/// میانبرهای سریع داشبورد یک کاربر — چرخهٔ چهل‌ویکم (گزارش مالک)
/// </summary>
/// <remarks>
/// «پنل میانبرهای سریع داشبورد در دیتابیس ذخیره بشه تا مشکلی براش پیش نیاد» —
/// تا چرخهٔ ۳۹ میانبرهای شخصی هر کاربر فقط در فایل محلی
/// %AppData%/SahandClinicPro/shortcuts.{username}.json نگه‌داری می‌شد؛ یعنی:
///   ۱) تعویض ویندوز/پاک‌شدن پروفایل = از دست رفتن چیدمان؛
///   ۲) ورود یک کاربر از دو ایستگاه = دو چیدمان ناهماهنگ؛
///   ۳) پشتیبان‌گیری سرور هیچ چیزی از این تنظیم شخصی را پوشش نمی‌داد.
/// این جدول حقیقت مرجع را به سرور می‌آورد: هر کاربر حداکثر یک ردیف دارد که
/// کلید صفحاتِ پین‌شدهٔ او را به‌صورت JSON آرایه‌ای نگه می‌دارد (مثلاً
/// ["receptions","appointments","billing"])؛ دسکتاپ فایل محلی را فقط به‌عنوان
/// کشِ آفلاین و منبع مهاجرتِ یک‌بارهٔ داده‌های قدیمی می‌خواند.
/// </remarks>
public class UserShortcut : AuditableEntity
{
    /// <summary>
    /// شناسهٔ کاربر مالک میانبرها — یکتا (ایندکس فیلترشده روی ردیف‌های سالم)؛
    /// کلید خارجی صریح ندارد تا موجودیت User دست‌نخورده بماند (همان سبک
    /// ارجاع نرم جداول هم‌خانواده مثل UserSessions در صورت پیکربندی).
    /// </summary>
    public long UserId { get; set; }

    /// <summary>
    /// کلید صفحات پین‌شده — آرایهٔ JSON از کلیدهای PageCatalog دسکتاپ؛
    /// سقف طول ۴۰۰۰ نویسه برای ده‌ها میانبر جا دارد (هر کلید ≤ ۳۰ نویسه).
    /// </summary>
    public string KeysJson { get; set; } = "[]";
}
